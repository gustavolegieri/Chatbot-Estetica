export function extractProviderImageResult(result: { data?: any; error?: any }) {
  const body = result?.data ?? null;
  const payloadImageUrl = typeof body?.imageUrl === 'string' && body.imageUrl.trim()
    ? body.imageUrl.trim()
    : null;
  const payloadProviderStatus = body?.providerStatus ?? body?.status ?? null;
  const hasSuccessfulPayload = Boolean(body && payloadImageUrl && (payloadProviderStatus === 200 || payloadProviderStatus === '200' || payloadProviderStatus === null));
  const sdkErrorMessage = String(result?.error?.message || result?.error || '');
  const hasSdkErrorWrapper = Boolean(result?.error) && !payloadImageUrl;

  const imageUrl = payloadImageUrl || null;
  const providerStatus = payloadProviderStatus ?? (hasSuccessfulPayload ? 200 : null);
  const providerMessage = String(body?.providerError || body?.error || body?.message || sdkErrorMessage || '');
  const shouldTreatAsSuccess = Boolean(imageUrl && (hasSuccessfulPayload || (!hasSdkErrorWrapper && !sdkErrorMessage)));

  return {
    imageUrl,
    providerStatus,
    providerMessage,
    shouldTreatAsSuccess,
    hasSdkErrorWrapper,
  };
}

export function isTrustedImageUrl(imageUrl: string | null | undefined, provider: string | null | undefined): boolean {
  if (!imageUrl) return false;
  const normalized = imageUrl.toLowerCase();
  if (provider === 'unsplash-search-image') {
    return normalized.includes('images.unsplash.com') || normalized.includes('unsplash.com');
  }
  if (provider === 'pexels-search-image') {
    return normalized.includes('images.pexels.com') || normalized.includes('pexels.com');
  }
  if (provider === 'pixabay-search-image') {
    return normalized.includes('pixabay.com') || normalized.includes('cdn.pixabay.com');
  }
  if (provider === 'openverse-search-image') {
    return normalized.includes('openverse') || normalized.includes('creativecommons');
  }
  return false;
}

