function isBlacklistedImageUrl(imageUrl: string, providerMsg: string, providerFn?: string) {
  try {
    const url = new URL(imageUrl);
    const host = (url.hostname || '').toLowerCase();
    const path = (url.pathname || '').toLowerCase();
    const search = (url.search || '').toLowerCase();

    const domainBlacklist = ['shutterstock', 'gettyimages', 'getty', 'istockphoto', 'depositphotos', 'adobe', '123rf', 'dreamstime', 'alibaba', 'aliexpress'];
    for (const d of domainBlacklist) if (host.includes(d)) return `blacklisted_domain:${d}`;

    const packagingKeywords = ['perfume', 'parfum', 'bottle', 'packaging', 'box', 'label', 'carton', 'catalogo', 'catalog', 'cover', 'poster', 'banner', 'ad', 'advert', 'promo', 'pack', 'logo', 'brand', 'watermark'];

    // Objects / scenes we explicitly never want as section thumbnails
    const nonClothingObjects = ['tomato', 'vegetable', 'vegetables', 'fruit', 'fruta', 'frutas', 'hay', 'straw', 'bale', 'hay bale', 'straw bale', 'agriculture', 'farm', 'orchard', 'barn'];
    for (const k of nonClothingObjects) if (path.includes(k) || search.includes(k) || providerMsg.toLowerCase().includes(k)) return `non_clothing_object:${k}`;

    // Reject obvious social/video platform hosts or provider messages that indicate video
    const videoHosts = ['youtube.com', 'youtu.be', 'vimeo.com', 'tiktok.com', 'instagram.com', 'facebook.com', 'pinterest.com'];
    for (const vh of videoHosts) if (host.includes(vh)) return `video_host:${vh}`;
    if (/video|youtube|tiktok|vimeo|instagram|facebook|pinterest/.test(providerMsg.toLowerCase())) return 'provider_indicated_video';
    for (const k of packagingKeywords) if (path.includes(k) || search.includes(k) || providerMsg.toLowerCase().includes(k)) return `packaging_or_promo:${k}`;

    if (path.endsWith('.svg') || path.includes('typography') || path.includes('wordart') || path.includes('calligraphy')) return 'text_art';

    // Additional filename/path heuristics: many bad results are delivered
    // as thumbnails, covers, or video frames whose filename contains
    // words like "thumb", "thumbnail", "screenshot", "frame" or
    // resolution markers like "720p". Reject these proactively.
    const filename = (path.split('/').pop() || '').toLowerCase();
    const extMatch = filename.match(/\.([a-z0-9]+)$/);
    const ext = extMatch ? extMatch[1] : '';
    const videoExtensions = new Set(['mp4', 'webm', 'mov', 'mkv', 'flv', 'avi']);
    if (videoExtensions.has(ext)) return `video_extension:${ext}`;

    const thumbnailIndicators = ['thumb', 'thumbnail', 'screenshot', 'screen', 'still', 'frame', 'preview', 'poster', 'cover', 'crop', 'social'];
    for (const ind of thumbnailIndicators) if (filename.includes(ind)) return `thumbnail_indicator:${ind}`;

    // reject resolution markers (e.g. 720p, 1080p) and typical video-ish tokens
    if (/\b\d{3,4}p\b/.test(filename) || /(?:video|clip|trailer|screenrecord)/.test(filename)) return 'video_like_filename';

    // Reject filenames that are numeric frames or huge numeric sequences
    if (/frame[_-]?\d{2,}|^\d{6,}$/.test(filename)) return 'frame_sequence';

    return false;
  } catch {
    return false;
  }
}

export async function searchRealProvidersFallback(
  queries: string[],
  originalQuery: string,
  excludeUrls?: Set<string> | Iterable<string> | null,
  seed?: number,
  brokerOptions?: BrokerFallbackOptions,
): Promise<string | null> {
  const exclude = excludeUrls instanceof Set
    ? excludeUrls
    : new Set<string>(excludeUrls ? Array.from(excludeUrls) : []);
  const baseSeed = typeof seed === 'number' && Number.isFinite(seed) ? seed >>> 0 : hashString(originalQuery);
  const exclusions = Array.from(new Set([
    ...(Array.isArray(brokerOptions?.exclusions) ? brokerOptions!.exclusions! : []),
    ...(Array.isArray(brokerOptions?.forbid) ? brokerOptions!.forbid! : []),
  ])).slice(0, 40);
  const pageHint = ((baseSeed >>> 3) % 5) + 1;
  const candidateQueries = brokerOptions?.strictProductShot ? queries.slice(0, 2) : queries;
  let qIdx = 0;
  for (const fallbackQuery of candidateQueries) {
    let pIdx = 0;
    const providers = providerRotation(baseSeed, brokerOptions?.providerMode ?? 'default');
    const fastProviders = brokerOptions?.strictProductShot
      ? [PRIMARY_PROVIDER, ...providers.filter((provider) => provider !== PRIMARY_PROVIDER)]
      : providers;
    for (const providerFn of fastProviders) {
      const cooldown = providerCooldownUntil.get(providerFn) || 0;
      if (Date.now() < cooldown) { pIdx += 1; continue; }
      const providerSeed = (baseSeed + qIdx * 131 + pIdx * 977) >>> 0;
      try {
        const effectiveQuery = buildSearchQueryForContext(fallbackQuery, brokerOptions?.strictProductShot);
        const timeoutMs = providerFn === PRIMARY_PROVIDER ? 1600 : providerFn === 'duckduckgo-search-image' ? 1800 : 2200;
        const result = await invokeWithQueue(providerFn, {
          body: {
            query: (effectiveQuery.length > 120
              ? effectiveQuery.slice(0, 120).replace(/\s+\S*$/, '').trim()
              : effectiveQuery),
            exclude_urls: Array.from(exclude).slice(-120),
            exclude_terms: exclusions,
            seed: providerSeed,
            page: pageHint,
            // CORREÇÃO: `mode` agora é de fato propagado no body. Antes era
            // montado em brokerOptions e nunca chegava na edge function.
            // NOTA: a edge function duckduckgo-search-image atual ainda NÃO
            // lê este campo (ver refatoração dela em anexo) — mantenha os
            // dois arquivos sincronizados se algum outro provider passar a
            // usar `mode` no futuro.
            ...(brokerOptions?.mode ? { mode: brokerOptions.mode } : {}),
            ...(brokerOptions?.color ? { color: brokerOptions.color } : {}),
            ...(brokerOptions?.require?.length ? { require: brokerOptions.require } : {}),
          },
        }, { timeoutMs, retries: 0 });

        const parsed = extractProviderImageResult(result as { data?: any; error?: any });
        const providerStatus = parsed.providerStatus;
        const providerMessage = parsed.providerMessage;
        if (providerStatus === 429 || providerStatus === '429' || result.data?.skipped || /429|Too Many Requests|Throttle/i.test(providerMessage)) {
          if (providerFn !== 'pexels-search-image') {
            providerCooldownUntil.set(providerFn, Date.now() + PROVIDER_COOLDOWN_MS);
          }
          pIdx += 1;
          continue;
        }

        const imageUrl = parsed.imageUrl;
        if (parsed.shouldTreatAsSuccess && imageUrl && !exclude.has(imageUrl)) {
          const rejectReason = isBlacklistedImageUrl(imageUrl, providerMessage, providerFn as string);
          if (rejectReason) {
            console.log('[image-search:fallback] rejected image by url blacklist', { imageUrl, provider: providerFn, reason: rejectReason });
            pIdx += 1;
            continue;
          }
          if (!isTrustedImageUrl(imageUrl, providerFn)) {
            console.log('[image-search:fallback] rejected image by provider trust validation', { imageUrl, provider: providerFn });
            pIdx += 1;
            continue;
          }
          console.log('[image-search:fallback]', providerFn, 'ok', { query: fallbackQuery, original: originalQuery, seed: providerSeed });
          return imageUrl;
        }
        if (imageUrl && exclude.has(imageUrl)) { pIdx += 1; continue; }
        const errMsg = parsed.providerMessage;
        if (/429|Too Many Requests|Throttle/i.test(errMsg)) {
          if (providerFn !== 'pexels-search-image') {
            providerCooldownUntil.set(providerFn, Date.now() + PROVIDER_COOLDOWN_MS);
          }
        }
      } catch (err: any) {
        const msg = String(err?.message || err || '');
        if (/429|Throttle|Too Many/i.test(msg) && providerFn !== 'pexels-search-image') {
          providerCooldownUntil.set(providerFn, Date.now() + PROVIDER_COOLDOWN_MS);
        }
      }
      pIdx += 1;
    }
    qIdx += 1;
  }
  return null;
}

