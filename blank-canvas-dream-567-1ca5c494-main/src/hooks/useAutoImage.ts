type ProviderFn = typeof REAL_PROVIDERS[number];

const PROVIDER_ORDER_BY_MODE: Record<ProviderMode, ProviderFn[]> = {
  default: [PRIMARY_PROVIDER, 'duckduckgo-search-image', 'pixabay-search-image', 'unsplash-search-image'],
  duckduckgoOnly: ['duckduckgo-search-image'],
  pexelsOnly: [PRIMARY_PROVIDER],
};

export function getProviderOrder(seed: number, mode: ProviderMode = 'default'): ProviderFn[] {
  const imageProviders = PROVIDER_ORDER_BY_MODE[mode];
  if (mode === 'default') {
    const rest = imageProviders.slice(1);
    const offset = rest.length ? seed % rest.length : 0;
    return [imageProviders[0], ...rest.slice(offset), ...rest.slice(0, offset)] as ProviderFn[];
  }
  const offset = seed % imageProviders.length;
  const rotated = [...imageProviders.slice(offset), ...imageProviders.slice(0, offset)];
  return rotated as ProviderFn[];
}

function providerRotation(seed: number, mode: ProviderMode = 'default'): ProviderFn[] {
  return getProviderOrder(seed, mode);
}

