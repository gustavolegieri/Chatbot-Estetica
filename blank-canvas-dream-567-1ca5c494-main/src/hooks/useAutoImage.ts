/**
 * Query EN de fallback: literal traduzido + cor/tecido do PERFIL ÚNICO
 * (não mais extraído ad-hoc do nome da peça) + âncora "woman" SEMPRE.
 * Isso é o que corrige a inconsistência: se a peça não menciona cor,
 * antes a query saía sem cor; agora usa a cor âncora do diagnóstico.
 */
function buildQueryEN(pieceName: string, categoryKey: string | undefined, profile: DiagnosisImageProfile): string {
  const literalPT = cleanPieceNamePT(pieceName);
  const literalEN = translateLiteralEN(literalPT);
  const anchor = CATEGORY_ANCHOR_EN[categoryKey || ''] || 'woman fashion';
  const colorToken = /\b(navy|blue|black|white|grey|beige|brown|red|green|pink|violet|yellow|orange)\b/i
    .test(literalEN) ? '' : ` ${profile.colorEN}`;
  if (literalEN) return `${literalEN}${colorToken} ${anchor}`.replace(/\s+/g, ' ').trim();
  return `${profile.colorEN} ${anchor}`;
}

function uniqueQueries(values: Array<string | null | undefined>): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const raw of values) {
    const q = (raw || '').replace(/\s+/g, ' ').trim();
    if (!q) continue;
    const key = q.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(q);
  }
  return out;
}

/**
 * Ladder EN de fallback (Pexels/Unsplash/Pixabay). Encurta 1 token por
 * vez a partir do literal traduzido, sempre preservando a âncora
 * "woman"/categoria — nunca deixa uma query neutra em gênero passar
 * para um provedor que pode devolver foto masculina.
 */
function buildProgressiveFallbackQueries(
  primaryQuery: string,
  pieceName: string,
  categoryKey: string | undefined,
  profile: DiagnosisImageProfile,
): string[] {
  const literalPT = cleanPieceNamePT(pieceName);
  const literalEN = translateLiteralEN(literalPT);
  const literalTokensEN = literalEN.split(/\s+/).filter(Boolean);
  const anchor = CATEGORY_ANCHOR_EN[categoryKey || ''] || 'woman fashion';

  const ladder: Array<string | null> = [primaryQuery, `${literalEN} ${anchor}`.trim(), literalEN];
  for (let n = literalTokensEN.length - 1; n >= 1; n -= 1) {
    ladder.push(literalTokensEN.slice(0, n).join(' '));
  }
  ladder.push(`${profile.colorEN} ${anchor}`);
  ladder.push(anchor);
  return uniqueQueries(ladder).map((q) => q.split(/\s+/).slice(0, 6).join(' ').slice(0, 80));
}

